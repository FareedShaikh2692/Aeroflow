package com.aeroflow.checkin.service;

import com.aeroflow.checkin.domain.Checkin;
import com.google.zxing.BarcodeFormat;
import com.google.zxing.EncodeHintType;
import com.google.zxing.common.BitMatrix;
import com.google.zxing.qrcode.QRCodeWriter;
import com.lowagie.text.*;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;
import java.awt.Color;
import java.awt.image.BufferedImage;
import java.io.ByteArrayOutputStream;
import java.time.ZoneOffset;
import java.time.format.DateTimeFormatter;
import java.util.Locale;
import java.util.Map;
import org.springframework.stereotype.Component;

/** Renders an A5-landscape PDF boarding pass with a QR code carrying a simplified IATA BCBP string. */
@Component
public class BoardingPassRenderer {
    private static final Color NAVY = new Color(11, 31, 58);
    private static final Color ACCENT = new Color(37, 99, 235);
    private static final DateTimeFormatter DATE = DateTimeFormatter.ofPattern("dd MMM yyyy", Locale.ENGLISH).withZone(ZoneOffset.UTC);
    private static final DateTimeFormatter TIME = DateTimeFormatter.ofPattern("HH:mm 'UTC'", Locale.ENGLISH).withZone(ZoneOffset.UTC);

    public byte[] render(Checkin c) {
        try (ByteArrayOutputStream out = new ByteArrayOutputStream()) {
            Document doc = new Document(PageSize.A5.rotate(), 28, 28, 24, 24);
            PdfWriter.getInstance(doc, out);
            doc.open();
            Font brand = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 20, Color.WHITE);
            Font small = FontFactory.getFont(FontFactory.HELVETICA, 8, new Color(100, 116, 139));
            Font value = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 13, NAVY);
            Font big = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 30, NAVY);

            PdfPTable header = new PdfPTable(new float[]{3, 2});
            header.setWidthPercentage(100);
            PdfPCell h1 = new PdfPCell(new Phrase("AEROFLOW", brand));
            PdfPCell h2 = new PdfPCell(new Phrase("BOARDING PASS · " + c.getCabin(),
                    FontFactory.getFont(FontFactory.HELVETICA_BOLD, 10, Color.WHITE)));
            for (PdfPCell h : new PdfPCell[]{h1, h2}) {
                h.setBackgroundColor(NAVY);
                h.setBorder(Rectangle.NO_BORDER);
                h.setPadding(10);
                h.setVerticalAlignment(Element.ALIGN_MIDDLE);
            }
            h2.setHorizontalAlignment(Element.ALIGN_RIGHT);
            header.addCell(h1);
            header.addCell(h2);
            doc.add(header);

            PdfPTable body = new PdfPTable(new float[]{4, 2});
            body.setWidthPercentage(100);
            body.setSpacingBefore(12);

            PdfPTable info = new PdfPTable(3);
            info.setWidthPercentage(100);
            PdfPCell route = cell(new Phrase(c.getOrigin() + "  ✈  " + c.getDestination(), big), 3);
            info.addCell(route);
            info.addCell(field("PASSENGER", (c.getLastName() + "/" + c.getFirstName()).toUpperCase(), small, value, 2));
            info.addCell(field("BOOKING REF", c.getPnr(), small, value, 1));
            info.addCell(field("FLIGHT", c.getFlightNumber(), small, value, 1));
            info.addCell(field("DATE", DATE.format(c.getDepartureTime()), small, value, 1));
            info.addCell(field("DEPARTS", TIME.format(c.getDepartureTime()), small, value, 1));
            info.addCell(field("SEAT", c.getSeatNumber(), small, value, 1));
            info.addCell(field("GROUP", c.getBoardingGroup(), small, value, 1));
            info.addCell(field("BOARDING", TIME.format(c.getBoardingTime()), small, value, 1));
            info.addCell(field("GATE", c.getGate() == null ? "See screens" : c.getGate(), small, value, 1));
            info.addCell(field("SEQ", String.format("%03d", c.getSequenceNumber()), small, value, 1));
            info.addCell(field("PASS NO.", c.getBoardingPassNumber(), small,
                    FontFactory.getFont(FontFactory.HELVETICA_BOLD, 9, ACCENT), 1));
            PdfPCell left = new PdfPCell(info);
            left.setBorder(Rectangle.NO_BORDER);
            body.addCell(left);

            Image qr = Image.getInstance(qr(bcbp(c), 360), (Color) null);
            qr.scaleToFit(150, 150);
            PdfPCell right = new PdfPCell(qr, false);
            right.setBorder(Rectangle.LEFT);
            right.setBorderColor(new Color(203, 213, 225));
            right.setHorizontalAlignment(Element.ALIGN_CENTER);
            right.setVerticalAlignment(Element.ALIGN_MIDDLE);
            right.setPadding(10);
            body.addCell(right);
            doc.add(body);

            Paragraph foot = new Paragraph("Gate closes 20 minutes before departure. Demo boarding pass generated by the "
                    + "AeroFlow portfolio project - not valid for travel.", small);
            foot.setSpacingBefore(10);
            doc.add(foot);
            doc.close();
            return out.toByteArray();
        } catch (Exception e) {
            throw new IllegalStateException("Failed to render boarding pass", e);
        }
    }

    /** Simplified IATA Resolution 792 Bar Coded Boarding Pass payload. */
    static String bcbp(Checkin c) {
        String name = String.format("%-20.20s", (c.getLastName() + "/" + c.getFirstName()).toUpperCase());
        int julian = c.getDepartureTime().atZone(ZoneOffset.UTC).getDayOfYear();
        String carrier = c.getFlightNumber().substring(0, 2);
        String number = String.format("%-5s", c.getFlightNumber().substring(2));
        return "M1" + name + "E" + String.format("%-7s", c.getPnr()) + c.getOrigin() + c.getDestination() + carrier + " "
                + number + String.format("%03d", julian) + ("BUSINESS".equals(c.getCabin()) ? "J" : "Y")
                + String.format("%4s", c.getSeatNumber()).replace(' ', '0') + String.format("%05d", c.getSequenceNumber()) + "100";
    }

    private static BufferedImage qr(String data, int size) throws Exception {
        BitMatrix m = new QRCodeWriter().encode(data, BarcodeFormat.QR_CODE, size, size, Map.of(EncodeHintType.MARGIN, 1));
        BufferedImage img = new BufferedImage(size, size, BufferedImage.TYPE_INT_RGB);
        for (int x = 0; x < size; x++) for (int y = 0; y < size; y++) img.setRGB(x, y, m.get(x, y) ? 0x0B1F3A : 0xFFFFFF);
        return img;
    }

    private static PdfPCell cell(Phrase p, int colspan) {
        PdfPCell c = new PdfPCell(p);
        c.setColspan(colspan);
        c.setBorder(Rectangle.NO_BORDER);
        c.setPaddingBottom(8);
        return c;
    }

    private static PdfPCell field(String label, String v, Font small, Font value, int colspan) {
        Phrase p = new Phrase();
        p.add(new Chunk(label + "\n", small));
        p.add(new Chunk(v, value));
        PdfPCell c = cell(p, colspan);
        c.setPaddingBottom(6);
        return c;
    }
}
